const LANG_LOCALE = { ko: "ko-KR", en: "en-US", ja: "ja-JP", es: "es-ES" };
let LANG = "ko";

function resolveLang(setting) {
  if (setting && I18N[setting]) return setting;
  const sys = (navigator.language || "en").toLowerCase();
  return ["ko", "ja", "es"].find((l) => sys.startsWith(l)) || "en";
}

/** Translate `key`, filling {placeholders} from `vars`. Falls back to Korean, then the key itself. */
function t(key, vars = {}) {
  let v = I18N[LANG]?.[key] ?? I18N.ko[key] ?? key;
  if (typeof v === "object") v = vars.n === 1 ? v.one : v.other;
  return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

/** Backend errors arrive as "E:code" or "E:code|n|detail"; anything else is shown as-is. */
function tErr(e) {
  const s = String(e);
  if (!s.startsWith("E:")) return s;
  const [code, n, detail] = s.slice(2).split("|");
  const msg = t(`err.${code}`, { n: n !== undefined ? Number(n) : undefined });
  return detail ? `${msg} (${detail})` : msg;
}

const tagLabel = (id) => t(`tag.${id}`);

/** Static markup: data-i18n (text), data-i18n-title, data-i18n-ph (placeholder), data-i18n-aria. */
function applyStaticI18n(root = document) {
  document.documentElement.lang = LANG;
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll("[data-i18n-ph]")) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
}

